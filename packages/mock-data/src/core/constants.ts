export const adapterIdFor = (category: AdapterCategory): string => `mock-${category}`;

export function categoryForAdapterId(adapterId: string): AdapterCategory | undefined {
  return ADAPTER_CATEGORIES.find((category) => adapterIdFor(category) === adapterId || `mock-${category}` === adapterId);
}

