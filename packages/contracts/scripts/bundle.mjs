// Bundles the OpenAPI document (resolving all JSON Schema $refs) into dist/jarvis-api.bundled.yaml.
import fs from "node:fs";
import path from "node:path";
import { paths, parseYaml, readText, stringifyYaml } from "./lib/contract.mjs";
import { runRedocly } from "./lib/redocly.mjs";

const COMPONENT_PREFIX = "#/components/schemas/";

/**
 * Redocly names hoisted files "<file>.schema" and keeps our stable aliases as pure $ref entries.
 * Collapse the aliases so every schema exists once under its title, and drop the per-file
 * JSON Schema identifiers ($id/$schema) which are meaningless inside an OpenAPI document.
 */
export function normalizeBundle(doc) {
  const schemas = doc.components?.schemas ?? {};
  const renames = new Map();
  for (const [alias, value] of Object.entries(schemas)) {
    const ref = value?.$ref;
    if (typeof ref === "string" && ref.startsWith(COMPONENT_PREFIX) && Object.keys(value).length === 1) {
      renames.set(ref.slice(COMPONENT_PREFIX.length), alias);
    }
  }
  const collapsed = {};
  for (const [name, value] of Object.entries(schemas)) {
    if (renames.has(name)) continue; // hoisted "<file>.schema" copy, re-added below under its alias
    const target = value?.$ref?.startsWith(COMPONENT_PREFIX)
      ? value.$ref.slice(COMPONENT_PREFIX.length)
      : undefined;
    collapsed[name] = target !== undefined && renames.has(target) ? schemas[target] : value;
  }
  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (node && typeof node === "object") {
      const out = {};
      for (const [k, v] of Object.entries(node)) {
        if (k === "$ref" && typeof v === "string" && v.startsWith(COMPONENT_PREFIX)) {
          const name = v.slice(COMPONENT_PREFIX.length);
          out[k] = `${COMPONENT_PREFIX}${renames.get(name) ?? name}`;
        } else out[k] = rewrite(v);
      }
      return out;
    }
    return node;
  };
  const sortedNames = Object.keys(collapsed).sort((a, b) => a.localeCompare(b));
  const sorted = {};
  for (const name of sortedNames) {
    const { $id: _id, $schema: _schema, ...rest } = collapsed[name];
    sorted[name] = rest;
  }
  const result = rewrite({ ...doc, components: { ...doc.components, schemas: sorted } });
  return result;
}

export function bundleOpenapi(outFile = paths.bundledOpenapi) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  const raw = outFile + ".raw.yaml";
  const { status, stderr, stdout } = runRedocly(["bundle", paths.openapi, "-o", raw]);
  if (status !== 0 || !fs.existsSync(raw)) {
    throw new Error(`redocly bundle failed (exit ${status})\n${stdout}\n${stderr}`);
  }
  const doc = normalizeBundle(parseYaml(readText(raw)));
  fs.rmSync(raw);
  const header = "# GENERATED by scripts/bundle.mjs from openapi/jarvis-api.yaml - do not edit.\n";
  fs.writeFileSync(outFile, header + stringifyYaml(doc));
  return doc;
}

if (process.argv[1]?.endsWith("bundle.mjs")) {
  bundleOpenapi();
  console.log(`bundle: wrote ${path.relative(paths.root, paths.bundledOpenapi)}`);
}
