import { parse } from "yaml";
import type { HttpMethod, QueryParamSpec, RequiredRole, ResponseSpec, RouteSpec } from "./route-types";

type Json = Record<string, unknown>;

const METHODS = ["get", "post", "patch", "put", "delete"] as const;

const refName = (ref: unknown): string | null => {
  if (typeof ref !== "string") return null;
  const match = /^#\/components\/schemas\/([A-Za-z0-9_]+)$/.exec(ref);
  return match ? (match[1] ?? null) : null;
};

/**
 * Turns the bundled OpenAPI document into the flat route table the Control API dispatches on. The table is generated
 * (never hand-edited) and a test regenerates it from the contract to fail on drift.
 */
export function buildRouteTable(bundledYaml: string): RouteSpec[] {
  const doc = parse(bundledYaml) as Json;
  const components = (doc.components ?? {}) as Json;
  const resolve = (value: unknown, group: string): Json => {
    const node = value as Json;
    if (typeof node?.$ref === "string") {
      const name = (node.$ref as string).split("/").pop() ?? "";
      return ((components[group] as Json)?.[name] ?? {}) as Json;
    }
    return node ?? {};
  };

  const routes: RouteSpec[] = [];
  for (const [path, item] of Object.entries((doc.paths ?? {}) as Json)) {
    const pathItem = item as Json;
    for (const method of METHODS) {
      const op = pathItem[method] as Json | undefined;
      if (!op || typeof op.operationId !== "string") continue;
      const params = [...((pathItem.parameters as unknown[]) ?? []), ...((op.parameters as unknown[]) ?? [])].map((p) =>
        resolve(p, "parameters"),
      );
      const query: QueryParamSpec[] = params
        .filter((p) => p.in === "query")
        .map((p) => ({ name: p.name as string, required: p.required === true, schema: (p.schema ?? {}) as Json }));
      const headerNames = params.filter((p) => p.in === "header").map((p) => String(p.name).toLowerCase());
      const body = op.requestBody ? resolve(op.requestBody, "requestBodies") : null;
      const bodyJson = (body?.content as Json | undefined)?.["application/json"] as Json | undefined;
      const bodySchema = refName((bodyJson?.schema as Json | undefined)?.$ref);

      const responses: ResponseSpec[] = [];
      for (const [status, raw] of Object.entries((op.responses ?? {}) as Json)) {
        const response = resolve(raw, "responses");
        const content = (response.content ?? {}) as Json;
        const contentTypes = Object.keys(content);
        const json = content["application/json"] as Json | undefined;
        const schema = refName((json?.schema as Json | undefined)?.$ref);
        responses.push({
          status: Number(status),
          schema: schema ?? (contentTypes.includes("application/octet-stream") ? "binary" : null),
          contentTypes,
        });
      }

      const role = ((op["x-required-role"] as string | undefined) ?? "viewer") as RequiredRole;
      routes.push({
        operationId: op.operationId as RouteSpec["operationId"],
        method: method.toUpperCase() as HttpMethod,
        path,
        tag: ((op.tags as string[] | undefined)?.[0] ?? "default") as string,
        capability: (op["x-capability"] as string | undefined) ?? null,
        role,
        requiresSession: !(Array.isArray(op.security) && op.security.length === 0),
        pathParams: params.filter((p) => p.in === "path").map((p) => p.name as string),
        query,
        acceptsIfMatch: headerNames.includes("if-match"),
        acceptsIdempotencyKey: headerNames.includes("idempotency-key"),
        csrf: headerNames.includes("x-csrf-token"),
        requestBody: body && bodySchema ? { required: body.required === true, schema: bodySchema } : null,
        maxBodyBytes: typeof op["x-max-body-bytes"] === "number" ? (op["x-max-body-bytes"] as number) : null,
        responses,
      });
    }
  }
  return routes;
}

export function renderRouteTableModule(routes: readonly RouteSpec[]): string {
  return `// GENERATED by scripts/generate-route-table.ts from packages/contracts/dist/friday-api.bundled.yaml. Do not edit.
// Regenerate with: pnpm --filter @friday/control-api generate:routes (contracts:generate must have run first).
import type { RouteSpec } from "./route-types";

export const ROUTE_TABLE: readonly RouteSpec[] = ${JSON.stringify(routes, null, 2)};
`;
}
